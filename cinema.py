# Criacao da matriz do cinema
# 5 fileiras e 6 lugares por fileira
# 0 representa lugar livre
# 1 representa lugar ocupado

cinema = [[0 for coluna in range(6)] for fileira in range(5)]

print("Quantidade de fileiras:", len(cinema))
print("Lugares por fileira:", len(cinema[0]))

def exibir_lugares(matriz):
    print("\nMAPA DE ASSENTOS DO CINEMA")
    print(" 1 2 3 4 5 6")
    for i in range(5):
        print(i + 1, end=" ")
        for j in range(6):
            if matriz[i][j] == 0:
                print("L", end=" ")
            else:
                print("X", end=" ")
        print()


# FUNCAO PARA COMPRAR INGRESSO
def comprar_ingresso(cinema):
    exibir_lugares(cinema)
    fileira = int(input("Digite o numero da fileira (1 a 5): ")) - 1
    lugar = int(input("Digite o numero do lugar (1 a 6): ")) - 1

    if fileira < 0 or fileira >= 5 or lugar < 0 or lugar >= 6:
        print("Fileira ou lugar invalido!")
    elif cinema[fileira][lugar] == 0:
        cinema[fileira][lugar] = 1
        print("Reserva realizada com sucesso!")
    else:
        print("Lugar ja ocupado! Escolha outro assento.")


# FUNCAO PARA CANCELAR RESERVA
def cancelar_reserva(cinema):
    exibir_lugares(cinema)
    fileira = int(input("Digite o numero da fileira (1 a 5): ")) - 1
    lugar = int(input("Digite o numero do lugar (1 a 6): ")) - 1

    if fileira < 0 or fileira >= 5 or lugar < 0 or lugar >= 6:
        print("Fileira ou lugar invalido!")
    elif cinema[fileira][lugar] == 1:
        cinema[fileira][lugar] = 0
        print(f"Reserva do assento {fileira + 1}, lugar {lugar + 1} cancelada com sucesso!")
    else:
        print("O assento ja esta livre!")


# FUNCAO PARA CONTAR LUGARES
def contar_lugares(cinema):
    livres = 0
    ocupados = 0

    for x in range(5):
        for y in range(6):
            if cinema[x][y] == 0:
                livres = livres + 1
            else:
                ocupados = ocupados + 1

    print("Lugares livres:", livres)
    print("Lugares ocupados:", ocupados)


opcao = int(0)

while opcao != 4:
    print("\n-------------- C I N E M A --------------\n")
    print("MENU:")
    print("-----------------------")
    print("[ 1 ] - COMPRAR INGRESSO")
    print("[ 2 ] - CANCELAR RESERVA")
    print("[ 3 ] - CONSULTAS DISPONIBILIDADE")
    print("[ 4 ] - ENCERRAR")

    opcao = int(input(" Digite sua escolha | "))

    if opcao == 1:
        ## OPCAO 1 - COMPRAR INGRESSO
        print(" ---------- SALA 1 ----------")
        print("Escolha sua cadeira")
        comprar_ingresso(cinema)

    elif opcao == 2:
        ## OPCAO 2 - CANCELAR UMA RESERVA
        print(" ---------- SALA 1 ----------")
        print("Selecione sua reserva")
        cancelar_reserva(cinema)

    elif opcao == 3:
        ## OPCAO 3 - CONSULTAR DISPONIBILIDADE
        print(" ---------- SALA 1 ----------")
        exibir_lugares(cinema)
        contar_lugares(cinema)

    elif opcao == 4:
        ## OPCAO 4 - ENCERRAR
        print("Sessoes encerradas! Ate mais...")

    else:
        print("Informe uma opcao valida! Tente novamente")

